import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SOURCE_COMMIT = 'c205c36a445bff37f8e58a9ec829105cd4975c58';
const SOURCE_URL = `https://raw.githubusercontent.com/danielmiessler/SecLists/${SOURCE_COMMIT}/Passwords/Common-Credentials/xato-net-10-million-passwords-100000.txt`;
const EXPECTED_SHA256 = '1472aafa2561df5e3293aee252aee3ca660c12b399a283cf808bb01b39be388b';
const output = fileURLToPath(new URL(
  '../src/custom/pharmacy/provisioning/common-passwords.generated.ts',
  import.meta.url,
));

const response = await fetch(SOURCE_URL);
if (!response.ok) throw new Error(`password source download failed: HTTP ${response.status}`);
const text = await response.text();
const hash = createHash('sha256').update(text).digest('hex');
if (hash !== EXPECTED_SHA256) throw new Error(`password source checksum mismatch: ${hash}`);
const passwords = text.replace(/\n$/u, '').split('\n');
if (passwords.length !== 100_000 || new Set(passwords).size !== 100_000) {
  throw new Error('password source must contain exactly 100000 unique entries');
}

await writeFile(output, `// Generated by scripts/generate-common-passwords.mjs; do not edit.\n` +
  `// Source: ${SOURCE_URL}\n` +
  `// SHA-256: ${EXPECTED_SHA256}\n` +
  `export const COMMON_PASSWORDS_TEXT = ${JSON.stringify(passwords.join('\n'))};\n`);
